    /// </para>
    /// <para>
    /// 01 - Static
    /// </para>
    /// <para>
    /// 02 - Dynamic
    /// </para>
    /// <para>
    /// 03 - OOB (Out of Band)
    /// </para>
    /// <para>
    /// 04 - Decoupled
    /// </para>
    /// <para>
    /// 20 - OTP hosted at merchant end. (Rupay S2S flow)
