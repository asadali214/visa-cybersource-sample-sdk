    /// <para>
    /// It will contain one of the following values:
    /// - <c>1</c> (3D Secure Version 1.x (3DS 1.0))
    /// - <c>2</c> (EMV 3-D Secure (3DS 2.x))
    /// </para>
    /// </summary>
