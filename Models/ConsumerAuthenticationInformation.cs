    /// 01 - 250x400
    /// </para>
    /// <para>
    /// 02 - 390x400
    /// </para>
    /// <para>
    /// 03 - 500x600
    /// </para>
    /// <para>
    /// 04 - 600x400
    /// </para>
    /// <para>
    /// 05 - Full page
    /// </para>
    /// </summary>
