    /// the issuer the alternative authentication methods that the consumer used.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("challengeStatus")]
    [MaxLength(2)]
    public string? ChallengeStatus { get; init; }

