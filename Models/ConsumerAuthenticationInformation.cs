    /// </para>
    /// <para>
    /// N - Do not use Decoupled Authentication
    /// </para>
    /// <para>
    /// <b>Default Value</b>: N
    /// </para>
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
